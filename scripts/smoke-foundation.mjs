import { spawn } from "node:child_process";
import net from "node:net";
import { readdir } from "node:fs/promises";
import { smokeEnvironment } from "./smoke-environment.mjs";

function checkPostgres(url) {
  return new Promise((resolve, reject) => {
    const socket = net.createConnection({
      host: url.hostname,
      port: Number(url.port),
    });
    socket.setTimeout(3000);
    socket.once("connect", () => {
      socket.destroy();
      resolve();
    });
    socket.once("timeout", () => {
      socket.destroy();
      reject(new Error("Pending: disposable PostgreSQL is not responding"));
    });
    socket.once("error", () =>
      reject(
        new Error(
          "Pending: disposable PostgreSQL is unavailable; Docker/psql must be supplied by the development environment",
        ),
      ),
    );
  });
}

function command(args, env) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, args, { env, stdio: "pipe" });
    // Child output may contain connection credentials. Show only controlled status.
    let output = "";
    child.stdout.on("data", (data) => {
      output = (output + data).slice(-12000);
    });
    child.stderr.on("data", (data) => {
      output = (output + data).slice(-12000);
    });
    // The integration coordinator owns bounded build/start timers and its cleanup.
    // Killing that coordinator here would orphan its owned Next.js server.
    const timer =
      args[1] === "run" ? undefined : setTimeout(() => child.kill(), 180000);
    child.once("error", () => {
      clearTimeout(timer);
      reject(new Error("Required local Node command could not start"));
    });
    child.once("exit", (code) => {
      clearTimeout(timer);
      if (code === 0) {
        const metrics = output.match(
          /HGR_SMOKE_METRICS: original=\d+ processed=\d+ width=640 height=400/,
        );
        if (metrics) console.log(metrics[0]);
        resolve();
      } else if (
        /ERR_DLOPEN_FAILED|Application Control|application control policy/.test(
          output,
        )
      ) {
        reject(
          new Error(
            "Pending: Sharp native module is blocked by Windows Application Control (ERR_DLOPEN_FAILED)",
          ),
        );
      } else if (/uv_os_get_passwd/.test(output)) {
        reject(
          new Error(
            "Pending: sandbox blocks Node userInfo (uv_os_get_passwd); official Payload generator needs the normal local runtime",
          ),
        );
      } else {
        const stage = output.match(/HGR_SMOKE_STAGE_FAILED:([a-z-]+)/)?.[1];
        reject(
          new Error(
            `Local command failed${stage ? ` at ${stage}` : ""} (exit ${code ?? "timeout"}); inspect locally with synthetic environment only`,
          ),
        );
      }
    });
  });
}

try {
  const { database, storage, child } = smokeEnvironment();
  const mode = process.argv[2];
  if (
    mode &&
    ![
      "--migrate-only",
      "--generate-migration",
      "--generate-importmap",
    ].includes(mode)
  ) {
    throw new Error("Unknown smoke command option");
  }
  if (mode === "--generate-importmap") {
    await command(["node_modules/payload/bin.js", "generate:importmap"], child);
    console.log("Payload import map generated by the official generator");
  } else if (mode === "--generate-migration") {
    await command(
      ["node_modules/payload/bin.js", "migrate:create", "foundation"],
      child,
    );
    console.log(
      "Foundation schema migration generated; review and commit before applying",
    );
  } else {
    await checkPostgres(database);
    if (!mode) {
      try {
        const response = await fetch(`${storage.origin}/storage/v1/b`, {
          signal: AbortSignal.timeout(3000),
          redirect: "error",
        });
        if (
          !response.ok ||
          !String(response.headers.get("content-type")).includes("json")
        )
          throw new Error();
      } catch {
        throw new Error(
          "Pending: loopback GCS-compatible JSON API endpoint is unavailable or incompatible; no disk/cloud fallback",
        );
      }
    }
    const migrations = await readdir("src/migrations").catch(() => []);
    if (!migrations.some((name) => /^\d.*\.ts$/.test(name))) {
      throw new Error(
        "Pending: generated collection-schema migration is absent; use the guarded --generate-migration option on a compatible runtime, review and commit its output",
      );
    }
    await command(["node_modules/payload/bin.js", "migrate"], child);
    console.log(
      "Payload migration command completed against disposable loopback PostgreSQL",
    );
    if (!mode) {
      await command(
        ["node_modules/payload/bin.js", "run", "scripts/foundation-smoke.ts"],
        child,
      );
      console.log(
        "PASS: local PostgreSQL, external objects, processed image, production public/Admin routes, restart and exact cleanup",
      );
    }
  }
} catch (error) {
  console.error(
    error instanceof Error ? error.message : "Foundation smoke failed",
  );
  console.error(
    "PORT-01/PORT-03 integration remains pending; this is not an Exabytes or second-host result.",
  );
  process.exitCode = 1;
}
